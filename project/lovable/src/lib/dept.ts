export function normalizeDept(value?: string | null): string {
  const raw = String(value ?? '').trim();
  if (!raw) return 'التنفيذ اعتيادى';
  if ((DEPARTMENTS as readonly string[]).includes(raw)) return raw;
  const low = raw.toLowerCase();
  for (const [canon, keys] of ALIASES) if (keys.some(k => low.includes(k.toLowerCase()))) return canon;
  return 'التنفيذ اعتيادى';
}

export const isAllowanceDept = (d?: string | null) => ALLOWANCE_DEPARTMENTS.includes(normalizeDept(d));
